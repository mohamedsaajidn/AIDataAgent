"""Validates a join request - structured (left/right dataset, keys, how), not
freehand merge code, per the same "deterministic gate before generation"
pattern as chart_spec.py. The actual merge code is generated by
join_render.py once a spec passes here.
"""

ALLOWED_HOW = {"inner", "left", "right", "outer"}


def validate_join_spec(spec: dict, left_columns: set[str], right_columns: set[str]) -> tuple[dict | None, list[str]]:
    left_on = spec.get("left_on")
    right_on = spec.get("right_on")
    how = spec.get("how") or "left"

    if how not in ALLOWED_HOW:
        return None, [f"'{how}' isn't a supported join type - use inner, left, right, or outer."]
    if not left_on:
        return None, ["A join needs a key column from the current dataset."]
    if not right_on:
        return None, ["A join needs a key column from the other dataset."]
    if left_on not in left_columns:
        return None, [f"Column '{left_on}' doesn't exist in the current dataset."]
    if right_on not in right_columns:
        return None, [f"Column '{right_on}' doesn't exist in the other dataset."]

    return {"left_on": left_on, "right_on": right_on, "how": how}, []
